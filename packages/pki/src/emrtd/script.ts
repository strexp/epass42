/**
 * eMRTD `.perso` script writer.
 *
 * Assembles the LDS1/LDS2 sections consumed by
 * `card42.host.emrtd.perso.LdsScript` (`@instance`, `@doc`, `@dg`, `@sod`,
 * `@aa`, `@ca`, `@cardaccess`, `@cardsecurity`, `@record`, `@transparent`).
 */
import { bytesToHex } from '../codec/hex'
import type { Bytes } from '../codec/bytes'

/** The LDS application AIDs (ICAO Doc 9303-10 §5). */
export const AID = {
  lds1: 'A0000002471001',
  travel: 'A0000002472001',
  visa: 'A0000002472002',
  biometrics: 'A0000002472003',
} as const

/** The application role of a personalization section. */
export type PersoRole = keyof typeof AID

/** A data group to personalize. */
export interface PersoDataGroup {
  number: number
  bytes: Bytes
}

/** A LDS2 record or transparent EF to personalize. */
export interface PersoFile {
  fid: string
  bytes: Bytes
}

/** A CVCA Terminal Authentication trust point (DGI FF07/FF09 or FF0B/FF0C). */
export interface CvTrustPoint {
  /** Certification Authority Reference (ISO 8859-1). */
  car: string
  /** Effective Date, `YYMMDD`. */
  effective: string
  /** 4-byte relative authorization `[ePassport, Travel, Visa, Biometrics]`. */
  authorization: Bytes
  /** The secondary trust point slot. */
  secondary?: boolean
  /** EC: uncompressed public point (`04 || X || Y`). */
  publicKey?: Bytes
  /** RSA-PSS: modulus and exponent. */
  modulus?: Bytes
  exponent?: Bytes
}

/** One personalization section. */
export interface PersoSection {
  role: PersoRole
  aid?: string
  documentNumber: string
  /** YYMMDD, for the BAC/PACE seed. */
  dateOfBirth: string
  /** YYMMDD, for the BAC/PACE seed. */
  dateOfExpiry: string
  /**
   * Optional PACE Card Access Number (six digits, password reference 0x02).
   * Written only for the LDS1 (master file) section; PACE falls back to the MRZ
   * password of `documentNumber`/`dateOfBirth`/`dateOfExpiry` when absent.
   */
  can?: string
  dataGroups: PersoDataGroup[]
  /** EF.SOD content (`77`-wrapped CMS). */
  sod?: Bytes
  /** Active Authentication private key value (DGI FF02). */
  aaPrivateKey?: Bytes
  /** Active Authentication ECDSA P-256 private scalar (DGI FF0D). */
  aaEcKey?: Bytes
  /** Active Authentication algorithm (DGI FF0A); default `sha1` on the card. */
  aaAlgorithm?: 'sha1' | 'sha256' | 'ecdsa'
  /** Chip Authentication P-256 private scalar (DGI FF03). */
  caScalar?: Bytes
  /** EF.CardAccess content. */
  cardAccess?: Bytes
  /** EF.CardSecurity content. */
  cardSecurity?: Bytes
  /** ICC current date (DGI FF08), `YYMMDD`. */
  taDate?: string
  /** CVCA trust points (DGI FF07/FF09). */
  trustPoints?: CvTrustPoint[]
  records?: PersoFile[]
  transparent?: PersoFile[]
}

/** The static header documenting the script grammar. */
function header(): string[] {
  return [
    '# card42 eMRTD personalization script - generated by ePass 42.',
    '#',
    '#   @instance <AID-hex>          start a section (LDS1 default A0000002471001)',
    '#   @doc <MRZ document number>   BAC document number',
    '#   @dob <YYMMDD>                BAC date of birth',
    '#   @doe <YYMMDD>                BAC date of expiry',
    '#   @can <6 digits>              PACE Card Access Number (password ref 0x02)',
    '#   @dg <n> <hex>                EF.DG<n> content (DG1 mandatory)',
    '#   @sod <hex>                   EF.SOD content',
    '#   @aa <hex>                    AA private key (modLen || modulus || expLen || exponent)',
    '#   @aa-ec <hex>                 AA ECDSA P-256 private scalar (DGI FF0D)',
    '#   @aa-alg sha1|sha256|ecdsa    AA signature algorithm (DGI FF0A)',
    '#   @ca <hex>                    Chip Authentication P-256 private scalar (DGI FF03)',
    '#   @ta-date <YYMMDD>            ICC current date (DGI FF08)',
    '#   @cvca <W-hex> <CAR> <YYMMDD> <auth-hex> [secondary]',
    '#                                EC CVCA trust point (DGI FF07, or FF09 with "secondary")',
    '#   @cvca-rsa <n-hex> <e-hex> <CAR> <YYMMDD> <auth-hex> [secondary]',
    '#                                RSA-PSS CVCA trust point (DGI FF0B, or FF0C)',
    '#   @lds2 <role>                 LDS2 role: travel | visa | biometrics',
    '#   @cardaccess <hex>            EF.CardAccess content',
    '#   @cardsecurity <hex>          EF.CardSecurity content',
    '#   @record <fid> <hex>          append one LDS2 record',
    '#   @transparent <fid> <hex>     set one LDS2 transparent EF',
  ]
}

/** Renders one section's directive lines. */
function renderSection(section: PersoSection): string[] {
  const lines: string[] = []
  const role = section.role
  const aid = section.aid ?? AID[role]
  lines.push(`@instance ${aid.toUpperCase()}`)
  if (role !== 'lds1') lines.push(`@lds2 ${role}`)
  lines.push(`@doc ${section.documentNumber}`)
  lines.push(`@dob ${section.dateOfBirth}`)
  lines.push(`@doe ${section.dateOfExpiry}`)
  if (section.can) lines.push(`@can ${section.can}`)

  for (const group of [...section.dataGroups].sort((a, b) => a.number - b.number)) {
    lines.push(`@dg ${group.number} ${bytesToHex(group.bytes)}`)
  }
  if (section.sod) lines.push(`@sod ${bytesToHex(section.sod)}`)
  if (section.aaPrivateKey) lines.push(`@aa ${bytesToHex(section.aaPrivateKey)}`)
  if (section.aaEcKey) lines.push(`@aa-ec ${bytesToHex(section.aaEcKey)}`)
  if (section.aaAlgorithm) lines.push(`@aa-alg ${section.aaAlgorithm}`)
  if (section.caScalar) lines.push(`@ca ${bytesToHex(section.caScalar)}`)
  if (section.cardAccess) lines.push(`@cardaccess ${bytesToHex(section.cardAccess)}`)
  if (section.cardSecurity) lines.push(`@cardsecurity ${bytesToHex(section.cardSecurity)}`)
  if (section.taDate) lines.push(`@ta-date ${section.taDate}`)
  for (const trustPoint of section.trustPoints ?? []) {
    const suffix = trustPoint.secondary ? ' secondary' : ''
    if (trustPoint.publicKey) {
      lines.push(
        `@cvca ${bytesToHex(trustPoint.publicKey)} ${trustPoint.car} ${trustPoint.effective} ${bytesToHex(trustPoint.authorization)}${suffix}`,
      )
    } else if (trustPoint.modulus && trustPoint.exponent) {
      lines.push(
        `@cvca-rsa ${bytesToHex(trustPoint.modulus)} ${bytesToHex(trustPoint.exponent)} ${trustPoint.car} ${trustPoint.effective} ${bytesToHex(trustPoint.authorization)}${suffix}`,
      )
    }
  }
  for (const record of section.records ?? []) {
    lines.push(`@record ${record.fid.toUpperCase()} ${bytesToHex(record.bytes)}`)
  }
  for (const transparent of section.transparent ?? []) {
    lines.push(`@transparent ${transparent.fid.toUpperCase()} ${bytesToHex(transparent.bytes)}`)
  }
  return lines
}

/** Renders the complete eMRTD personalization script. */
export function renderEmrtdScript(sections: PersoSection[]): string {
  const lines = header()
  for (const section of sections) {
    lines.push('')
    lines.push(`# --- ${section.role} (${section.aid ?? AID[section.role]}) ---`)
    lines.push(...renderSection(section))
  }
  lines.push('')
  return lines.join('\n')
}
