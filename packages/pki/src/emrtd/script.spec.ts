import { describe, expect, it } from 'vitest'

import { buildDg1 } from './dg'
import type { MrzFields } from './mrz'
import { renderEmrtdScript } from './script'

describe('eMRTD perso script', () => {
  it('renders the Terminal Authentication directives', () => {
    const script = renderEmrtdScript([
      {
        role: 'lds1',
        documentNumber: 'L898902C<',
        dateOfBirth: '690806',
        dateOfExpiry: '940623',
        dataGroups: [],
        taDate: '240101',
        trustPoints: [
          {
            publicKey: new Uint8Array([0x04, ...new Array(64).fill(0x11)]),
            car: 'UTCVCA0000000001',
            effective: '240101',
            authorization: new Uint8Array([0x03, 0x0f, 0x0f, 0x0f]),
          },
          {
            publicKey: new Uint8Array([0x04, ...new Array(64).fill(0x22)]),
            car: 'UTCVCA0000000002',
            effective: '240201',
            authorization: new Uint8Array([0x00, 0x0f, 0x00, 0x00]),
            secondary: true,
          },
        ],
      },
    ])
    expect(script).toContain('@ta-date 240101')
    expect(script).toContain('@cvca 04')
    expect(script).toContain('UTCVCA0000000001 240101 030F0F0F')
    expect(script).toContain('UTCVCA0000000002 240201 000F0000 secondary')
  })

  it('renders the AA algorithm and RSA-PSS trust-point directives', () => {
    const script = renderEmrtdScript([
      {
        role: 'lds1',
        documentNumber: 'L898902C<',
        dateOfBirth: '690806',
        dateOfExpiry: '940623',
        dataGroups: [],
        aaEcKey: new Uint8Array(32).fill(0xaa),
        aaAlgorithm: 'ecdsa',
        trustPoints: [
          {
            modulus: new Uint8Array([0x00, 0x81, 0x02]),
            exponent: new Uint8Array([0x01, 0x00, 0x01]),
            car: 'XDRSADV000000001',
            effective: '240301',
            authorization: new Uint8Array([0x00, 0x00, 0x00, 0x00]),
          },
        ],
      },
    ])
    expect(script).toContain(`@aa-ec ${'AA'.repeat(32)}`)
    expect(script).toContain('@aa-alg ecdsa')
    expect(script).toMatch(/^@cvca-rsa 008102 010001 XDRSADV000000001 240301 00000000$/m)
  })

  it('keeps only the header, LDS section markers and MRZ comments', () => {
    const td3: MrzFields = {
      documentCode: 'P',
      issuingState: 'UTO',
      surname: 'ERIKSSON',
      givenNames: 'ANNA MARIA',
      documentNumber: 'L898902C',
      nationality: 'UTO',
      dateOfBirth: '690806',
      sex: 'F',
      dateOfExpiry: '940623',
      personalNumber: 'ZE184226B',
    }
    const script = renderEmrtdScript([
      {
        role: 'lds1',
        documentNumber: 'L898902C<',
        dateOfBirth: '690806',
        dateOfExpiry: '940623',
        dataGroups: [{ number: 1, bytes: buildDg1(td3) }],
      },
    ])

    expect(
      script.startsWith('# card42 eMRTD personalization script - generated by ePass 42.'),
    ).toBe(true)
    expect(script).toContain('# --- lds1 (A0000002471001) ---')
    expect(script).toContain('# MRZ TD3')
    expect(script).toContain('# P<UTOERIKSSON<<ANNA<MARIA')
    expect(script).toContain('# L898902C<3UTO6908061F9406236ZE184226B<<<<<14')
    // The field-by-field grammar explanations are gone.
    expect(script).not.toContain('BAC document number')
    expect(script).not.toContain('@instance <AID-hex>')
    expect(script).not.toMatch(/^# {3}@/m)
  })

  it('labels TD1 MRZ comments and keeps LDS2 section markers', () => {
    const td1: MrzFields = {
      documentCode: 'ID',
      issuingState: 'UTO',
      surname: 'ERIKSSON',
      givenNames: 'ANNA MARIA',
      documentNumber: 'D23145890',
      nationality: 'UTO',
      dateOfBirth: '740812',
      sex: 'F',
      dateOfExpiry: '120415',
    }
    const script = renderEmrtdScript([
      {
        role: 'lds1',
        documentNumber: 'D23145890',
        dateOfBirth: '740812',
        dateOfExpiry: '120415',
        dataGroups: [{ number: 1, bytes: buildDg1(td1) }],
      },
      {
        role: 'travel',
        documentNumber: 'D23145890',
        dateOfBirth: '740812',
        dateOfExpiry: '120415',
        dataGroups: [],
      },
    ])

    expect(script).toContain('# MRZ TD1')
    expect(script).toContain('# IDUTOD231458907<<<<<<<<<<<<<<<')
    expect(script).toContain('# 7408122F1204159UTO<<<<<<<<<<<6')
    expect(script).toContain('# ERIKSSON<<ANNA<MARIA<<<<<<<<<<')
    expect(script).toContain('# --- travel (A0000002472001) ---')
    expect(script.match(/# MRZ TD1/g)).toHaveLength(1)
  })
})
